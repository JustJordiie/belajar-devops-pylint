"""Modul demonstrasi fungsi yang telah diperbaiki."""

def fungsi_bagus(nilai_a, nilai_b):
    """Menjumlahkan dua nilai.
    Args:
        nilai_a: Angka pertama.
        nilai_b: Angka kedua.
    Returns:
        Hasil penjumlahan.
    """
    return nilai_a + nilai_b

if __name__ == "__main__":
    fungsi_bagus(1, 2)